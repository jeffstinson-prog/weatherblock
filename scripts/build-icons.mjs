const root = join(import.meta.dirname, '..');
const dir = process.argv[2] ?? join(root, 'node_modules', 'lucide-static', 'icons');
const out = {};
for (const name of ICONS) {
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<svg[\s\S]*?>/, '')
    .replace(/<\/svg>/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>')
    .trim();
  out[name] = inner;
}
const body = Object.entries(out)
  .map(([k, v]) => `  '${k}': '${v.replace(/'/g, "\\'")}',`)
  .join('\n');
writeFileSync(
  join(root, 'src', 'icons', 'data.ts'),
  `// Generated by scripts/build-icons.mjs from Lucide (https://lucide.dev), ISC license,\n// copyright (c) Lucide Icons and Contributors. Don't edit by hand.\nexport const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
